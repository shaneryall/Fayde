"""Write THIRD-PARTY-LICENSES.md: the licences of every third-party crate in Cargo.lock.

    python3 scripts/gen_third_party_licenses.py           # rewrite the file and its copy
    python3 scripts/gen_third_party_licenses.py --check   # exit 1 if either is out of date

Fayde's binaries and wheels are statically linked, so they carry code from these crates; their
licences ask for the copyright notice and licence text to travel with copies. The file is built
from `cargo metadata --locked` and the licence files each crate ships, so it lists every crate
of every platform, build-time ones included. Run it after any change to Cargo.lock.

A copy goes next to the Python project (`crates/fayde-py/`), because a wheel can only carry
licence files from its own directory. Uses only the standard library.
"""

import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUTS = [ROOT / "THIRD-PARTY-LICENSES.md", ROOT / "crates" / "fayde-py" / "THIRD-PARTY-LICENSES.md"]
PREFIXES = ("LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "NOTICE", "UNLICENSE")


def packages():
    """Third-party packages of the locked dependency graph, sorted by name and version."""
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    meta = json.loads(out)
    ours = set(meta["workspace_members"])
    third = [p for p in meta["packages"] if p["id"] not in ours]
    return sorted(third, key=lambda p: (p["name"], p["version"]))


def licence_files(package):
    """(file name, text) of each licence file in the crate's source, sorted by name."""
    crate = pathlib.Path(package["manifest_path"]).parent
    found = []
    for f in sorted(crate.iterdir(), key=lambda f: f.name):
        if f.is_file() and f.name.upper().startswith(PREFIXES):
            text = f.read_text(encoding="utf-8", errors="replace")
            text = "\n".join(line.rstrip() for line in text.replace("\r\n", "\n").split("\n")).strip("\n")
            found.append((f.name, text))
    return found


def render():
    pkgs = packages()
    lines = [
        "# Third-party licences",
        "",
        "Fayde's binaries and Python wheels are statically linked: they contain code from the Rust",
        "crates below, or were built with them. Each crate is used under the licence it offers;",
        "where a crate offers a choice, the texts of all its options are given. Fayde itself is",
        "licensed under the Apache License 2.0 (`LICENSE`, `NOTICE`).",
        "",
        "Generated by `scripts/gen_third_party_licenses.py` from `Cargo.lock`. Do not edit.",
        "",
        "| Crate | Version | Licence | Source |",
        "|---|---|---|---|",
    ]
    texts = {}
    missing = []
    for p in pkgs:
        if not p.get("license"):
            missing.append(f"{p['name']} {p['version']}: no licence expression")
        lines.append(
            f"| {p['name']} | {p['version']} | {p.get('license') or '?'} | {p.get('repository') or ''} |"
        )
        files = licence_files(p)
        if not files:
            missing.append(f"{p['name']} {p['version']}: no licence file in the crate")
        for name, text in files:
            digest = hashlib.sha256(text.encode()).hexdigest()
            texts.setdefault(digest, (text, []))[1].append((p["name"], p["version"], name))
    if missing:
        raise SystemExit("cannot write the licence file:\n  " + "\n  ".join(missing))
    lines += ["", "## Licence texts", ""]
    for text, users in sorted(texts.values(), key=lambda v: v[1]):
        fence = "```"
        while fence in text:
            fence += "`"
        lines.append("### " + "; ".join(f"{c} {v} ({n})" for c, v, n in users))
        lines += ["", fence + "text", text, fence, ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    check = "--check" in sys.argv[1:]
    text = render()
    stale = [o for o in OUTPUTS if not o.is_file() or o.read_text(encoding="utf-8") != text]
    if check:
        if stale:
            names = ", ".join(str(o.relative_to(ROOT)) for o in stale)
            raise SystemExit(f"out of date: {names}\nrun: python3 scripts/gen_third_party_licenses.py")
        print(f"third-party licences are up to date ({len(OUTPUTS)} files)")
        return
    for o in OUTPUTS:
        o.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(OUTPUTS)} files, {len(text)} bytes each")


if __name__ == "__main__":
    main()
